def outcome_cell(kind: str, r) -> str:
    if kind == "fused":
        states = [s for c in r["chains"] for s in c["states"]]
        return f"\\cmark{{}} {len(states)} states"
    if kind == "refused":
        return "\\markRefused{} overflow (huge inputs)"
    if kind == "frontend":
        why = r["skipped"][0]["reason"]
        why = why.replace("intrinsic tirx.", "").replace("intrinsic prim.", "").replace("non-trivial index expression", "index")
        why = why.replace("loop variable used as a real value", "loop variable as value")
        return f"\\markFrontend{{}} \\texttt{{{tex_escape(why)}}}"
    if kind == "notchain":
        return "\\markFrontend{} two-axis reduction"
    return "no verified state tuple"


def prior_table(pr, prior_outcome) -> None:
    lines = ["% generated by Hapax/scripts/gen_tex.py from data/prior.json -- do not edit"]
    for paper in ("Neptune", "RedFuser"):
        rs = [r for r in pr if r["paper"] == paper]
        lines.append(f"\\multicolumn{{4}}{{@{{}}l}}{{\\textit{{{paper}}}}}\\\\")
        for r in rs:
            kind = prior_outcome(r)
            lines.append(
                f"\\quad {DISPLAY.get(r['key'], tex_escape(r['what']))} & {tex_escape(r['where'])} & "
                f"{r['spelling']} & {outcome_cell(kind, r)}\\\\"
            )
        if paper == "Neptune":
            lines.append("\\midrule")
    write_rows("tab-prior", "tabPriorRows", lines)


def registry_table(fused, acc_rows) -> None:
    acc = {a["name"]: a for a in acc_rows}
    lines = ["% generated by Hapax/scripts/gen_tex.py from data/fused_ops.json -- do not edit"]
    for r in sorted(fused, key=lambda r: (INFO[r["name"]][1], r["name"])):
        name, dom = INFO[r["name"]]
        states = ", ".join(s for c in r["chains"] for s in c["states"])
        auxs = {a for c in r["chains"] for a in c["auxiliaries"]}
        st = ", ".join(f"\\aux{{{tex_escape(s)}}}" if s in auxs else tex_escape(s) for s in states.split(", "))
        mech = MECH_NAME[mechanism([a for c in r["chains"] for a in c["actions"]])]
        a = acc[r["name"]]
        rc = "--" if a["ratio_c"] is None else f"{a['ratio_c']:.2f}"
        ro = "--" if a["ratio_o"] is None else f"{a['ratio_o']:.2f}"
        mark = "$^\\star$" if r.get("showcase") else ""
        lines.append(
            f"{tex_escape(name)}{mark} & {dom} & {sum(r['passes_before'])}$\\to${sum(r['passes_after'])} & "
            f"\\texttt{{\\scriptsize {st}}} & {mech} & {rc} & {ro}\\\\"
        )
    write_rows("tab-registry", "tabRegistryRows", lines)


def write_rows(name: str, macro: str, lines: list[str]) -> None:
    """Table rows as a macro: a \\multicolumn must come first in its cell, which an
    \\input inside a tabular does not allow."""
    body = [l for l in lines if not l.startswith("%")]
    text = lines[0] + "\n" + f"\\newcommand{{\\{macro}}}{{%\n" + "\n".join(body) + "\n}\n"
    (GEN / f"{name}.tex").write_text(text, encoding="utf-8")


def unfused_table(un, outcome) -> None:
    """Every program that is not fused, with the tool's own reason (shortened)."""
    label = {
        "unknown": "no single pass is known",
        "refused": "refused",
        "notread": "no chain read",
        "unsupported": "unsupported input",
        "noselect": "no state set",
        "fused": "fused at HEAD",
        "other": "other",
    }
    lines = ["% generated by Hapax/scripts/gen_tex.py from data/unfused.json -- do not edit"]
    for r in un:
        kind = outcome(r)
        why = ""
        if kind == "unknown":
            why = "; ".join(t for t in r.get("theory", []) if t)
        elif kind in ("refused", "noselect", "other"):
            why = "; ".join(c.get("reason") or "" for c in r.get("chains", []) if not c.get("fused"))
        elif kind in ("unsupported", "notread"):
            why = r.get("raised") or "; ".join(s.get("reason", "") for s in r.get("skipped", []))
        elif kind == "fused":
            why = r.get("summary", "").splitlines()[0] if r.get("summary") else ""
        why = re.sub(r"\s+", " ", why)
        if len(why) > 150:
            why = why[:147] + "..."
        name = tex_escape(r["key"].split(" ", 1)[-1])
        name = name.replace("\\_", "\\_\\allowbreak{}").replace("[", "\\allowbreak[")
        lines.append(
            f"\\texttt{{{name}}} & {r['source']} & {label[kind]} & {{\\scriptsize {tex_escape(why)}}}\\\\"
        )
    write_rows("tab-unfused", "tabUnfusedRows", lines)


def showcase_table(fused, acc_rows) -> None:
    """Compact coverage table, including the measured state-discovery route."""
    lines = ["% generated by Hapax/scripts/gen_tex.py from data/fused_ops.json -- do not edit"]
    rows = [r for r in fused if r.get("showcase")]
    for r in sorted(rows, key=lambda r: (INFO[r["name"]][1], r["name"])):
        name, _ = INFO[r["name"]]
        if not r.get("fused"):
            lines.append(f"{tex_escape(name)} & --- & --- & --- & --- & not fused" + r"\\")
            continue
        added = sum(len(c["auxiliaries"]) for c in r["chains"])
        nst = sum(len(c["states"]) for c in r["chains"])
        base = BASELINES.get(r["name"]) or ", ".join(r["showcase"]["baselines"][:3]) or "---"
        routes = list(dict.fromkeys(c.get("route", "unrecorded") for c in r["chains"]))
        route = "/".join({"original": "source", "rebase": "closure", "sygus": "synthesis"}.get(v, v) for v in routes)
        lines.append(
            f"{tex_escape(name)} & {tex_escape(base)} & "
            f"{sum(r['passes_before'])}" + r"$\to$" + f"{sum(r['passes_after'])} & {nst} & {added} & {route}" + r"\\"
        )
    write_rows("tab-showcase", "tabShowcaseRows", lines)


def hazard_table(hz) -> None:
    """Inputs the acceptance check does not sample: errors of the three forms."""

    def cell(x) -> str:
        return "$\\infty$" if x is None or math.isinf(x) else f"${sci(x)}$"

    lines = ["% generated by Hapax/scripts/gen_tex.py from data/hazards.json -- do not edit"]
    for h in hz:
        name = INFO[h["operator"]][0]
        fused = "" if h["fused"] else " (not fused)"
        lines.append(
            f"{tex_escape(name)}{fused} & {tex_escape(h['input'])} & {cell(h['unfused'])} & "
            f"{cell(h.get('hand'))} & {cell(h['synthesised'])}\\\\"
        )
    write_rows("tab-hazards", "tabHazardRows", lines)


def new_states_text(auxs: list[str]) -> str:
    """The states a reducer adds to the program's own, by kind."""
    kinds = Counter("count" if a == "count" else a.split(".")[-1][0] for a in auxs)
    parts = []
    if kinds.get("count"):
        parts.append("count")
    for key, one, many in [
        ("r", "1 supplemented coefficient", "supplemented coefficients"),
        ("h", "1 hoisted coefficient", "hoisted coefficients"),
        ("m", "1 part of a max", "parts of a max"),
    ]:
        n = kinds.get(key, 0)
        if n == 1:
            parts.append(one)
        elif n > 1:
            parts.append(f"{n} {many}")
    return ", ".join(parts) if parts else "none"


