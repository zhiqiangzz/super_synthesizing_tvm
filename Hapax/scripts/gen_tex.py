    M.add("nShowcaseDomains", len({INFO[r["name"]][1] for r in show}), "info_en.py domains of the showcase rows")
    M.add("showPassesBefore", sum(sum(r["passes_before"]) for r in show), "showcase: sum of passes_before")
    M.add("showPassesAfter", sum(sum(r["passes_after"]) for r in show), "showcase: sum of passes_after")
    M.add("showChains", sum(len(r["chains"]) for r in show), "showcase: chains")
    M.add("showStates", sum(len(c["states"]) for r in show for c in r["chains"]), "showcase: states")
    M.add("showDerived", len(show_aux), "showcase: auxiliaries")
    M.add("showDerivedOps", sum(1 for r in show if any(c["auxiliaries"] for c in r["chains"])), "showcase rows with auxiliaries")
    M.add("showNoStep", sum(1 for r in show if not any(c["actions"] for c in r["chains"])), "showcase rows without a selection step")
    sel_show = [r["t_select"]["median"] for r in pt if r["name"] in show_names]
    M.add("showSelectMaxMs", f"{max(sel_show) * 1e3:.0f}", "showcase: max median select time, ms")
    M.add("showSelectMedianMs", f"{statistics.median(sel_show) * 1e3:.0f}", "showcase: median of median select times, ms")
    fuse_show = [r["t_fuse"]["median"] for r in pt if r["name"] in show_names]
    M.add("showFuseSinkhorn", num(next(r["t_fuse"]["median"] for r in pt if r["name"] == "sinkhorn_iteration"), 1), "showcase: sinkhorn_iteration median fuse time, s")
    M.add("showFuseMax", num(max(fuse_show)), "accepted showcase: max median fuse time, s")
    M.add("showFuseMedian", num(statistics.median(fuse_show)), "accepted showcase: median fuse time, s")
    jud_show = [r["t_judge"]["median"] for r in pt if r["name"] in show_names]
    M.add("showJudgeMaxMs", num(max(jud_show) * 1e3, 1), "showcase: max median judge time, ms")
    inv_show = Counter(c["invariant_proof"] for r in pt if r["name"] in show_names for c in r["chains"] if c["selected"])
    M.add("showInvCanonical", inv_show.get("canonical", 0), "showcase: invariants proven by canonical identity")
    acc_show = [a for a in acc_rows if a["name"] in show_names]
    M.add("showRatioLeOne", sum(1 for a in acc_show if a["ratio_c"] is not None and a["ratio_c"] <= 1), "showcase: centred ratio <= 1")
    M.add("showGateWorstMargin", num(max(a["margin"] for a in acc_show), 3), "showcase: worst candidate/bound")
    tf = [(r["t_fuse"]["median"], r["name"]) for r in pt]
    tf_rest = [t for t, n in tf if not n.startswith("sinkhorn_i") and not n.startswith("sinkhorn_s")]
    tf_sink = [t for t, n in tf if n in ("sinkhorn_iteration", "sinkhorn_square")]
    M.add("timeJudgeMaxMs", num(max(tj) * 1e3, 1), "max median judge time, ms")
    M.add("timeJudgeMedianMs", num(statistics.median(tj) * 1e3, 1), "median of median judge times, ms")
    M.add("timeSelectMedianMs", f"{statistics.median(ts) * 1e3:.0f}", "median of median select times, ms")
    M.add("timeSelectMaxMs", f"{max(ts) * 1e3:.0f}", "max median select time, ms")
    M.add("timeFuseMedian", num(statistics.median([t for t, _ in tf])), "median fuse time, s")
    M.add("timeFuseMin", num(min(tf_rest)), "min fuse time excluding the two Sinkhorn iterations, s")
    M.add("timeFuseMax", num(max(tf_rest)), "max fuse time excluding the two Sinkhorn iterations, s")
