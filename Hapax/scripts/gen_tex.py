"""Turn Hapax/data/*.json into LaTeX macros, tables and CSV (standard library only).

Every macro in gen/stats.tex is followed by a ``% src:`` line naming the file and
the computation it comes from. Data whose ``meta.commit`` is not the current HEAD,
or that was produced from a dirty tool tree, is refused unless ``--allow-stale``
is given (the paper then prints a STALE banner; ``build.sh --submit`` never passes
that flag).

    python3 -I Hapax/scripts/gen_tex.py [--allow-stale]
"""

