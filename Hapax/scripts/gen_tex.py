    show_names = {r["name"] for r in show}
    for route, macro in (("original", "showOriginalOps"), ("rebase", "showRebaseOps"), ("sygus", "showSygusOps")):
        count = (sum(all(c.get("route") == route for c in r["chains"]) for r in show)
                 if all("route" in c for r in show for c in r["chains"]) else "unrecorded")
        M.add(macro, count, f"fused_ops.json showcase operators with every chain route = {route}")
