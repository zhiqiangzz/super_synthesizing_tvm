def load(name: str) -> dict:
    return json.load(open(DATA / f"{name}.json", encoding="utf-8"))


def head() -> str:
    return subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=HAPAX.parent, capture_output=True, text=True, check=True
    ).stdout.strip()


class Macros:
    def __init__(self) -> None:
        self.lines: list[str] = ["% generated by Hapax/scripts/gen_tex.py -- do not edit"]
        self.names: set[str] = set()

    def add(self, name: str, value, src: str) -> None:
        assert re.fullmatch(r"[A-Za-z]+", name), name
        assert name not in self.names, name
        self.names.add(name)
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}\\xspace}}")
        self.lines.append(f"%   src: {src}")

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


def sci(x: float, digits: int = 1) -> str:
    """1.2e-07 -> 1.2\\times10^{-7}, as math."""
    if x == 0:
        return "0"
    if math.isinf(x):
        return "\\infty"
    if math.isnan(x):
        return "\\mathrm{NaN}"
    e = int(math.floor(math.log10(abs(x))))
    m = x / 10**e
    if round(m, digits) >= 10:
        m, e = m / 10, e + 1
    return f"{m:.{digits}f}\\times10^{{{e}}}"


def num(x: float, digits: int = 2) -> str:
    return f"{x:.{digits}f}"


TEX_CHARS = {
    "\\": "\\textbackslash{}",
    "^": "\\textasciicircum{}",
    "~": "\\textasciitilde{}",
    "Σ": "$\\Sigma$",
    "·": "$\\cdot$",
    "≤": "$\\le$",
    "≥": "$\\ge$",
    "−": "$-$",
}


def tex_escape(s: str) -> str:
    """Text for LaTeX text mode, one character at a time."""
    out = []
    for ch in s:
        if ch in TEX_CHARS:
            out.append(TEX_CHARS[ch])
        elif ch in "&%#_{}$":
            out.append("\\" + ch)
        else:
            out.append(ch)
    return "".join(out)


def main() -> None:
    allow_stale = "--allow-stale" in sys.argv
    GEN.mkdir(exist_ok=True)
    data = {n: load(n) for n in FILES}
    commit = head()
    stale = []
    for n, d in data.items():
        m = d.get("meta", {})
